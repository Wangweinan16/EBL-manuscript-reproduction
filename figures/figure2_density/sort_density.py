def parse_csv_choices(raw: str, valid: set[str], label: str) -> list[str]:
    if raw.lower() == "all":
        return sorted(valid)
    values = [part.strip() for part in raw.split(",") if part.strip()]
    bad = [value for value in values if value not in valid]
    if bad:
        raise ValueError(f"Unknown {label}: {bad}. Valid: {sorted(valid)}")
    return values


def resolve_spikegadgets_rec_file(input_path: Path) -> Path:
    input_path = Path(input_path)
    if not input_path.exists():
        raise FileNotFoundError(f"Recording path does not exist: {input_path}")
    if input_path.suffix.lower() != ".rec":
        raise ValueError(f"Recording path must end with '.rec': {input_path}")
    if input_path.is_file():
        return input_path
    nested_same_name_file = input_path / input_path.name
    if nested_same_name_file.exists() and nested_same_name_file.is_file():
        return nested_same_name_file
    rec_file_candidates = sorted([p for p in input_path.glob("*.rec") if p.is_file()])
    if len(rec_file_candidates) == 1:
        return rec_file_candidates[0]
    if len(rec_file_candidates) == 0:
        raise ValueError(f"No .rec file found inside .rec directory: {input_path}")
    raise ValueError(f"Multiple .rec files found inside directory: {input_path}")


def forward_conversion(hw_chan: int, totalchan: int) -> int:
    num_cards = totalchan // 32
    return ((hw_chan % 32) * num_cards) + (hw_chan // 32)


def reverse_conversion(new_hw_chan: int, totalchan: int) -> int:
    num_cards = totalchan // 32
    return (new_hw_chan % num_cards) * 32 + (new_hw_chan // num_cards)


def select_recording_channels(recording, channel_ids, renamed_channel_ids=None):
    channel_ids = list(channel_ids)
    if renamed_channel_ids is not None:
        renamed_channel_ids = list(renamed_channel_ids)
    if hasattr(recording, "select_channels"):
        selected = recording.select_channels(channel_ids)
        if renamed_channel_ids is not None and hasattr(selected, "rename_channels"):
            return selected.rename_channels(renamed_channel_ids)
        return selected
    if hasattr(recording, "channel_slice"):
        return recording.channel_slice(
            channel_ids=channel_ids,
            renamed_channel_ids=renamed_channel_ids,
        )
    raise AttributeError("Recording has neither select_channels nor channel_slice")


def reorganize_spikegadgets_recording(rec_raw):
    totalchan = rec_raw.get_num_channels()
    hw_chans = np.arange(totalchan)
    new_hw_chans = [forward_conversion(hw_chan, totalchan) for hw_chan in hw_chans]
    reverse_hw_chans = [
        reverse_conversion(new_hw_chan, totalchan) for new_hw_chan in new_hw_chans
    ]
    if not np.all(np.asarray(reverse_hw_chans) == hw_chans):
        raise RuntimeError("Channel reorganization validation failed.")
    channel_ids_rec = rec_raw.get_channel_ids()
    new_channel_order = [channel_ids_rec[c] for c in new_hw_chans]
    return select_recording_channels(rec_raw, new_channel_order)


def load_layout(layout: str, layout_dir: Path) -> dict[str, Any]:
    channel_json = layout_dir / f"layout_{layout}_channels.json"
    probe_json = layout_dir / f"NET-EBL-1-{layout}-fig2e.json"
    if not channel_json.exists():
        raise FileNotFoundError(f"Missing layout metadata: {channel_json}")
    if not probe_json.exists():
        raise FileNotFoundError(f"Missing layout probe JSON: {probe_json}")
    metadata = read_json(channel_json)
    metadata["channel_json"] = str(channel_json)
    metadata["probe_json"] = str(probe_json)
    return metadata


def make_ms5_params(recording_duration_s: float, alternate_params: bool) -> dict[str, Any]:
    scheme2_training_sec = min(300.0, max(5.0, recording_duration_s * 0.95))
    return {
        "scheme": "2",
        "detect_sign": -1,
        "detect_threshold": 4.5 if alternate_params else 5.5,
        "npca_per_channel": MS5_NPCA_PER_CHANNEL,
        "npca_per_subdivision": MS5_NPCA_PER_SUBDIVISION,
        "snippet_mask_radius": 10 if alternate_params else 100,
        "scheme1_detect_channel_radius": 15 if alternate_params else 150,
        "scheme2_phase1_detect_channel_radius": 20 if alternate_params else 200,
        "scheme2_detect_channel_radius": 10 if alternate_params else 100,
        "scheme2_training_duration_sec": scheme2_training_sec,
        "filter": False,
        "whiten": True,
    }


def load_recording(rec_path: Path, debug_duration_sec: float | None, se):
    rec_file = resolve_spikegadgets_rec_file(rec_path)
    rec_loaded = se.read_spikegadgets(file_path=str(rec_file))
    rec_raw = CustomSamplingFrequencyRecording(rec_loaded, SAMPLING_RATE)
    rec_raw.set_channel_gains(DEFAULT_GAIN_TO_UV)
    rec_raw.set_channel_offsets(0)
    if debug_duration_sec is not None:
        end_frame = int(float(debug_duration_sec) * SAMPLING_RATE)
        end_frame = min(end_frame, rec_raw.get_num_frames())
        rec_raw = rec_raw.frame_slice(start_frame=0, end_frame=end_frame)
    rec_hwmapped = reorganize_spikegadgets_recording(rec_raw)
    rec_hwmapped.set_channel_gains(DEFAULT_GAIN_TO_UV)
    rec_hwmapped.set_channel_offsets(0)
    return rec_file, rec_hwmapped


def prepare_layout_recording(rec_hwmapped, layout_metadata: dict[str, Any], read_probeinterface):
    selected_channel_ids = [
        int(ch) for ch in layout_metadata["sliced_probe_device_channel_indices"]
    ]
    recording_channel_ids = list(rec_hwmapped.get_channel_ids())
    channel_id_by_int = {int(ch): ch for ch in recording_channel_ids}
    missing = [ch for ch in selected_channel_ids if ch not in channel_id_by_int]
    if missing:
        raise RuntimeError(f"Selected channels are absent from recording: {missing}")
    recording_selection_ids = [channel_id_by_int[ch] for ch in selected_channel_ids]
    rec_layout = select_recording_channels(
        rec_hwmapped,
        recording_selection_ids,
        renamed_channel_ids=selected_channel_ids,
    )
    probe = read_probeinterface(layout_metadata["probe_json"]).probes[0]
    probe_device_indices = [int(ch) for ch in probe.device_channel_indices]
    if probe_device_indices != selected_channel_ids:
        raise RuntimeError(
            "Reduced probe device_channel_indices do not match selected channels."
        )
    probe_for_recording = probe.copy()
    probe_for_recording.set_device_channel_indices(
        np.arange(len(selected_channel_ids), dtype=int)
    )
    rec_layout = rec_layout.set_probe(probe_for_recording, in_place=True)
    return rec_layout, probe, selected_channel_ids


