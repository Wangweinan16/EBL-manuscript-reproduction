def run_sorter_only(
    output_folder: Path,
    recording,
    ms5_params: dict[str, Any],
    create_analyzer: bool,
    sorter_backend: str,
) -> None:
    import spikeinterface as si

    saved_recording_folder = output_folder / "saved_recording"
    sorter_output_folder = output_folder / "sorter_output"
    sorted_sorting_folder = output_folder / "sorted_sorting"
    sorting_npz_file = output_folder / "sorted_units.npz"
    print(f"Saving preprocessed recording: {saved_recording_folder}", flush=True)
    with timed_step("save preprocessed recording to binary"):
        rec_sorter_input = recording.save(
            folder=saved_recording_folder,
            format="binary",
            overwrite=True,
        )
    print(f"Running MountainSort5 ({sorter_backend})...", flush=True)
    sorting_t0 = time.perf_counter()
    if sorter_backend == "spikeinterface":
        _, ss = import_sorter_modules()
        sorting = ss.run_sorter(
            sorter_name="mountainsort5",
            recording=rec_sorter_input,
            output_folder=sorter_output_folder,
            remove_existing_folder=True,
            verbose=False,
            **ms5_params,
        )
    elif sorter_backend == "ms5-direct":
        sorting = run_mountainsort5_direct(
            rec_sorter_input,
            sorter_output_folder,
            ms5_params,
        )
    else:
        raise ValueError(f"Unknown sorter backend: {sorter_backend}")
    print(f"MountainSort5 time: {format_elapsed(time.perf_counter() - sorting_t0)}")
    with timed_step("save sorting outputs"):
        sorting.save(folder=sorted_sorting_folder, overwrite=True)
        si.NpzSortingExtractor.write_sorting(sorting, sorting_npz_file)
    print(f"Saved sorting with {sorting.get_num_units()} units to {sorted_sorting_folder}")
    if create_analyzer:
        with timed_step("create analyzer and SI plots"):
            create_analyzer_and_si_plots(rec_sorter_input, sorting, output_folder)
    else:
        with timed_step("extract waveforms and lightweight unit plots"):
            extract_and_plot_units(rec_sorter_input, sorting, output_folder)


def run_mountainsort5_direct(recording, sorter_output_folder: Path, ms5_params: dict[str, Any]):
    import mountainsort5 as ms5
    import spikeinterface.preprocessing as spre
    import spikeinterface as si

    sorter_output_folder.mkdir(parents=True, exist_ok=True)
    recording_for_ms5 = spre.whiten(recording=recording, dtype="float32")
    scheme = str(ms5_params.get("scheme", "2"))
    if scheme != "2":
        raise ValueError("ms5-direct currently supports only scheme 2")

    sorting_parameters = ms5.Scheme2SortingParameters(
        phase1_detect_channel_radius=ms5_params["scheme2_phase1_detect_channel_radius"],
        detect_channel_radius=ms5_params["scheme2_detect_channel_radius"],
        phase1_detect_threshold=ms5_params["detect_threshold"],
        phase1_detect_time_radius_msec=0.5,
        detect_time_radius_msec=0.5,
        phase1_npca_per_channel=ms5_params["npca_per_channel"],
        phase1_npca_per_subdivision=ms5_params["npca_per_subdivision"],
        detect_sign=ms5_params["detect_sign"],
        detect_threshold=ms5_params["detect_threshold"],
        snippet_T1=20,
        snippet_T2=20,
        snippet_mask_radius=ms5_params["snippet_mask_radius"],
        max_num_snippets_per_training_batch=200,
        classifier_npca=None,
        training_duration_sec=ms5_params["scheme2_training_duration_sec"],
        training_recording_sampling_mode="uniform",
    )
    sorting = ms5.sorting_scheme2(
        recording=recording_for_ms5,
        sorting_parameters=sorting_parameters,
    )
    si.NpzSortingExtractor.write_sorting(sorting, sorter_output_folder / "firings.npz")
    return sorting


def safe_compute_extension(analyzer, extension_name: str, **kwargs) -> None:
    if analyzer.has_extension(extension_name):
        print(f"Extension already present: {extension_name}", flush=True)
        return
    t0 = time.perf_counter()
    print(f"Computing analyzer extension: {extension_name}", flush=True)
    try:
        analyzer.compute(extension_name, **kwargs)
        print(
            f"Finished analyzer extension: {extension_name} "
            f"({format_elapsed(time.perf_counter() - t0)})",
            flush=True,
        )
    except Exception as exc:
        print(f"[warning] Could not compute extension '{extension_name}': {exc}", flush=True)


def ensure_pipeline_unit_summary_extensions(analyzer) -> None:
    safe_compute_extension(analyzer, "noise_levels")
    safe_compute_extension(
        analyzer,
        "principal_components",
        n_components=3,
        mode="by_channel_local",
    )
    safe_compute_extension(analyzer, "template_similarity", method="cosine_similarity")
    safe_compute_extension(analyzer, "spike_amplitudes", peak_sign="both")
    safe_compute_extension(
        analyzer,
        "template_metrics",
        include_multi_channel_metrics=True,
    )
    safe_compute_extension(analyzer, "unit_locations", method="monopolar_triangulation")
    safe_compute_extension(
        analyzer,
        "correlograms",
        window_ms=50.0,
        bin_ms=1.0,
        method="auto",
    )
    safe_compute_extension(
        analyzer,
        "isi_histograms",
        window_ms=50.0,
        bin_ms=1.0,
        method="auto",
    )
    if analyzer.has_extension("noise_levels"):
        safe_compute_extension(
            analyzer,
            "quality_metrics",
            qm_params={
                "snr": {"peak_sign": "both"},
                "amplitude_median": {"peak_sign": "both"},
            },
        )
    else:
        print("[warning] Skipping quality_metrics because noise_levels is unavailable.")


def create_analyzer_and_si_plots(recording, sorting, output_folder: Path) -> None:
    import spikeinterface as si
    import spikeinterface.widgets as sw

    if sorting.get_num_units() == 0:
        print("No units detected; skipping analyzer and SI widget plots.")
        return

    analyzer_folder = output_folder / "sorting_analyzer.zarr"
    print(f"Creating sorting analyzer: {analyzer_folder}", flush=True)
    analyzer = si.create_sorting_analyzer(
        sorting=sorting,
        recording=recording,
        format="zarr",
        folder=analyzer_folder,
        overwrite=True,
    )
    safe_compute_extension(analyzer, "random_spikes", method="uniform", max_spikes_per_unit=500)
    safe_compute_extension(
        analyzer,
        "waveforms",
        ms_before=WAVEFORM_EXTRACT_MS_BEFORE,
        ms_after=WAVEFORM_EXTRACT_MS_AFTER,
    )
    safe_compute_extension(analyzer, "templates", operators=["average", "median", "std"])
    ensure_pipeline_unit_summary_extensions(analyzer)

    summary_folder = output_folder / "unit_summary_before_curation_si_widget_analyzer"
    summary_folder.mkdir(parents=True, exist_ok=True)
    n_summary = 0
    unit_ids = list(sorting.get_unit_ids())
    for i, unit_id in enumerate(unit_ids, start=1):
        plot_t0 = time.perf_counter()
        print(
            f"Saving SI unit summary {i}/{len(unit_ids)} for unit {unit_id}",
            flush=True,
        )
        sw.plot_unit_summary(analyzer, unit_id=unit_id, backend="matplotlib")
        plt.savefig(summary_folder / f"unit_summary_{int(unit_id)}.png", dpi=300, bbox_inches="tight")
        plt.close()
        n_summary += 1
        print(
            f"Saved SI unit summary {i}/{len(unit_ids)} "
            f"({format_elapsed(time.perf_counter() - plot_t0)})",
            flush=True,
        )
    print(f"Saved {n_summary} SI analyzer unit summary plot(s) to {summary_folder}")

    save_analyzer_unit_waveform_plots(analyzer, output_folder)


def save_analyzer_unit_waveform_plots(analyzer, output_folder: Path) -> None:
    if not analyzer.has_extension("waveforms"):
        print("[warning] No waveforms extension; skipping analyzer waveform plots.")
        return
    waveforms_ext = analyzer.get_extension("waveforms")
    channel_ids = np.asarray(analyzer.channel_ids)
    waveform_folder = output_folder / "unit_waveforms_before_curation_analyzer"
    waveform_folder.mkdir(parents=True, exist_ok=True)

    n_saved = 0
    for unit_id in analyzer.sorting.get_unit_ids():
        try:
            waveforms_u = waveforms_ext.get_waveforms_one_unit(unit_id)
        except Exception:
            waveforms_u = None
        if waveforms_u is None or getattr(waveforms_u, "size", 0) == 0:
            continue
        mean_wf = waveforms_u.mean(axis=0)
        best_channel_index = int(np.argmax(np.max(np.abs(mean_wf), axis=0)))
        best_channel_id = (
            int(channel_ids[best_channel_index])
            if best_channel_index < len(channel_ids)
            else best_channel_index
        )
        single_channel_wfs = waveforms_u[:, :, best_channel_index]
        avg_wf = np.mean(single_channel_wfs, axis=0)
        time_ms = np.linspace(
            -WAVEFORM_EXTRACT_MS_BEFORE,
            WAVEFORM_EXTRACT_MS_AFTER,
            len(avg_wf),
        )

        fig, ax = plt.subplots(figsize=(4, 6), dpi=300)
        for wf in single_channel_wfs:
            ax.plot(time_ms, wf, color="gray", alpha=0.05, linewidth=0.4)
        ax.plot(time_ms, avg_wf, color="red", linewidth=2)
        ax.set_xlabel("Time (ms)")
        ax.set_ylabel("Amplitude (uV)")
        ax.set_title(f"Unit {int(unit_id)} | ch {best_channel_id}")
        fig.savefig(
            waveform_folder / f"unitwf_hw{best_channel_id}_unit{int(unit_id)}.png",
            dpi=300,
            bbox_inches="tight",
        )
        plt.close(fig)
        n_saved += 1
    print(f"Saved {n_saved} analyzer waveform plot(s) to {waveform_folder}")


def extract_and_plot_units(recording, sorting, output_folder: Path) -> None:
    import spikeinterface as si

    if sorting.get_num_units() == 0:
        print("No units detected; skipping waveform and unit-summary plots.")
        return

    waveforms_folder = output_folder / "waveforms_before_curation"
    unit_waveform_folder = output_folder / "unit_waveforms_before_curation"
    unit_summary_folder = output_folder / "unit_summary_before_curation"
    unit_waveform_folder.mkdir(parents=True, exist_ok=True)
    unit_summary_folder.mkdir(parents=True, exist_ok=True)
    (unit_summary_folder / "bad_unit").mkdir(parents=True, exist_ok=True)

    print(f"Extracting waveforms for unit plots: {waveforms_folder}", flush=True)
    waveforms = si.extract_waveforms(
        recording,
        sorting,
        folder=waveforms_folder,
        overwrite=True,
        ms_before=WAVEFORM_EXTRACT_MS_BEFORE,
        ms_after=WAVEFORM_EXTRACT_MS_AFTER,
        max_spikes_per_unit=500,
        return_scaled=True,
        sparse=False,
        allow_unfiltered=True,
    )

    fs = float(recording.get_sampling_frequency())
    duration_s = recording.get_num_frames() / fs
    channel_ids = np.asarray(recording.get_channel_ids())
    ms_before = float(WAVEFORM_EXTRACT_MS_BEFORE)
    ms_after = float(WAVEFORM_EXTRACT_MS_AFTER)

    n_waveform_plots = 0
    n_summary_plots = 0
    for unit_id in sorting.get_unit_ids():
        unit_waveforms = waveforms.get_waveforms(unit_id)
        if unit_waveforms is None or unit_waveforms.size == 0:
            continue
        template = waveforms.get_template(unit_id)
        n_samples = template.shape[0]
        time_ms = np.linspace(-ms_before, ms_after, n_samples)
        p2p_by_channel = np.ptp(template, axis=0)
        best_channel_index = int(np.argmax(p2p_by_channel))
        best_channel_id = (
            int(channel_ids[best_channel_index])
            if best_channel_index < len(channel_ids)
            else best_channel_index
        )
        best_waveforms = unit_waveforms[:, :, best_channel_index]
        best_template = template[:, best_channel_index]
        spike_train = sorting.get_unit_spike_train(unit_id=unit_id)
        spike_times_s = np.asarray(spike_train, dtype=float) / fs
        firing_rate_hz = len(spike_train) / duration_s if duration_s > 0 else np.nan
        peak_p2p_uv = float(p2p_by_channel[best_channel_index])

        waveform_path = (
            unit_waveform_folder
            / f"unitwf_hw{best_channel_id}_unit{int(unit_id)}.png"
        )
        fig, ax = plt.subplots(figsize=(4.0, 5.5), dpi=300)
        for wf in best_waveforms:
            ax.plot(time_ms, wf, color="0.55", alpha=0.08, linewidth=0.4)
        ax.plot(time_ms, best_template, color="red", linewidth=1.5)
        ax.set_xlabel("Time (ms)")
        ax.set_ylabel("Amplitude (uV)")
        ax.set_title(f"Unit {int(unit_id)} | ch {best_channel_id}")
        fig.savefig(waveform_path, dpi=300, bbox_inches="tight")
        plt.close(fig)
        n_waveform_plots += 1

        summary_path = unit_summary_folder / f"unit_summary_{int(unit_id)}.png"
        fig, axes = plt.subplots(2, 2, figsize=(9.0, 7.0), dpi=300)
        ax = axes[0, 0]
        for wf in best_waveforms:
            ax.plot(time_ms, wf, color="0.6", alpha=0.06, linewidth=0.35)
        ax.plot(time_ms, best_template, color="red", linewidth=1.4)
        ax.set_title(f"Best channel {best_channel_id}")
        ax.set_xlabel("Time (ms)")
        ax.set_ylabel("Amplitude (uV)")

        ax = axes[0, 1]
        im = ax.imshow(
            template.T,
            aspect="auto",
            origin="lower",
            extent=[time_ms[0], time_ms[-1], 0, template.shape[1] - 1],
            cmap="RdBu_r",
        )
        ax.set_title("Mean template")
        ax.set_xlabel("Time (ms)")
        ax.set_ylabel("Local channel index")
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04, label="uV")

        ax = axes[1, 0]
        if len(spike_times_s) > 1:
            isi_ms = np.diff(spike_times_s) * 1000.0
            ax.hist(isi_ms, bins=np.linspace(0, min(100, max(5, np.nanmax(isi_ms))), 40), color="0.25")
        ax.set_title("ISI histogram")
        ax.set_xlabel("ISI (ms)")
        ax.set_ylabel("Count")

        ax = axes[1, 1]
        ax.eventplot(spike_times_s, colors="black", linewidths=0.7)
        ax.set_xlim(0, max(duration_s, 1e-9))
        ax.set_yticks([])
        ax.set_xlabel("Time (s)")
        ax.set_title(
            f"spikes={len(spike_train)}, FR={firing_rate_hz:.2f} Hz, "
            f"P2P={peak_p2p_uv:.1f} uV"
        )

        fig.suptitle(f"Unit {int(unit_id)} summary", y=0.98)
        fig.tight_layout()
        fig.savefig(summary_path, dpi=300, bbox_inches="tight")
        plt.close(fig)
        n_summary_plots += 1

    print(
        f"Saved {n_waveform_plots} waveform plot(s) to {unit_waveform_folder}",
        flush=True,
    )
    print(
        f"Saved {n_summary_plots} unit summary plot(s) to {unit_summary_folder}",
        flush=True,
    )
    print(
        f"Manual curation folder ready: {unit_summary_folder / 'bad_unit'}",
        flush=True,
    )


def run_one_job_impl(
    animal: AnimalSession,
    layout: str,
    layout_dir: Path,
    output_root: Path,
    debug_duration_sec: float | None,
    run_sorter: bool,
    alternate_params: bool,
    enable_noisy_segment_cleaning: bool,
    create_analyzer: bool,
    sorter_backend: str,
    skip_existing: bool,
) -> None:
    total_t0 = time.perf_counter()
    with timed_step("import SpikeInterface/probe modules"):
        se, spre, read_probeinterface, plot_probe = import_light_modules()
    with timed_step("load layout metadata"):
        layout_metadata = load_layout(layout, layout_dir)
    run_tag = (
        f"debug_{int(debug_duration_sec)}s" if debug_duration_sec is not None else "full"
    )
    output_folder = output_root / animal.animal / f"layout_{layout}" / run_tag
    output_folder.mkdir(parents=True, exist_ok=True)

    if run_sorter and skip_existing and has_existing_sorting(output_folder):
        print(
            f"[skip-existing] Found existing sorted_sorting and sorted_units.npz for "
            f"{animal.animal} layout {layout} ({run_tag}); skipping job.",
            flush=True,
        )
        print(f"Output folder: {output_folder}", flush=True)
        return

    print(f"Loading {animal.animal} from {animal.rec_path}", flush=True)
    with timed_step("load .rec and hardware-map channels"):
        rec_file, rec_hwmapped = load_recording(animal.rec_path, debug_duration_sec, se)
    with timed_step("select layout channels and attach probe"):
        rec_layout, probe, selected_channel_ids = prepare_layout_recording(
            rec_hwmapped,
            layout_metadata,
            read_probeinterface,
        )
    recording_duration_s = rec_layout.get_num_frames() / float(
        rec_layout.get_sampling_frequency()
    )
    ms5_params = make_ms5_params(recording_duration_s, alternate_params)
    metadata = {
        "created_at": datetime.now().isoformat(timespec="seconds"),
        "script": str(Path(__file__).resolve()),
        "animal": animal.animal,
        "layout": layout,
        "run_tag": run_tag,
        "source_rec": str(rec_file),
        "layout_dir": str(layout_dir),
        "layout_channel_json": layout_metadata["channel_json"],
        "layout_probe_json": layout_metadata["probe_json"],
        "mapping_strategy": layout_metadata.get("mapping_strategy"),
        "selection_interpretation": layout_metadata.get("selection_interpretation"),
        "recovered_channel_ids": layout_metadata.get("recovered_channel_ids"),
        "mapped_contact_indices": layout_metadata.get("contact_indices"),
        "selected_channel_ids": selected_channel_ids,
        "probe_original_device_channel_indices": [
            int(ch) for ch in probe.device_channel_indices
        ],
        "probe_attached_device_channel_indices": list(
            range(len(selected_channel_ids))
        ),
        "num_channels": int(rec_layout.get_num_channels()),
        "sampling_frequency": float(rec_layout.get_sampling_frequency()),
        "duration_s": float(recording_duration_s),
        "gain_to_uv": DEFAULT_GAIN_TO_UV,
        "debug_duration_sec": debug_duration_sec,
        "alternate_ms5_params": bool(alternate_params),
        "enable_noisy_segment_cleaning": bool(enable_noisy_segment_cleaning),
        "waveform_extract_ms_before": WAVEFORM_EXTRACT_MS_BEFORE,
        "waveform_extract_ms_after": WAVEFORM_EXTRACT_MS_AFTER,
        "ms5_params": ms5_params,
        "run_sorter": bool(run_sorter),
        "sorter_backend": sorter_backend,
        "create_analyzer": bool(create_analyzer),
        "postprocessing_status": (
            "requested_analyzer_extensions_and_si_widget_plots"
            if create_analyzer
            else "first_pass_sort_waveformextractor_plots_only"
        ),
        "output_folder": str(output_folder),
    }
    with timed_step("write run metadata"):
        write_json(output_folder / "fig2e_sort_run_metadata.json", metadata)
    print(
        f"Prepared {animal.animal} layout {layout}: "
        f"{rec_layout.get_num_channels()} channels, {recording_duration_s:.2f} s, "
        f"output={output_folder}",
        flush=True,
    )

    with timed_step("bandpass for visualization"):
        rec_vis = spre.bandpass_filter(rec_layout, freq_min=300, freq_max=6000)
    with timed_step("save probe layout plot"):
        save_probe_plot(probe, output_folder / "probe_layout.png", plot_probe)
    with timed_step("save raw trace plot"):
        save_trace_plot(rec_vis, output_folder / "trace_plot.png")

    if not run_sorter:
        print("[dry-run] Prepared metadata, probe plot, and trace plot only.")
        return

    with timed_step("preprocess for sorting"):
        rec_sorting = preprocess_for_sorting(
            rec_layout,
            enable_noisy_segment_cleaning=enable_noisy_segment_cleaning,
            spre=spre,
        )
    with timed_step("save post-preprocessing trace plot"):
        save_trace_plot(rec_sorting, output_folder / "trace_plot_post_preprocessing.png")
    with timed_step("run sorter and extract unit plots"):
        run_sorter_only(
            output_folder,
            rec_sorting,
            ms5_params,
            create_analyzer=create_analyzer,
            sorter_backend=sorter_backend,
        )
    print(f"Job time: {format_elapsed(time.perf_counter() - total_t0)}")


def run_one_job(
    animal: AnimalSession,
    layout: str,
    layout_dir: Path,
    output_root: Path,
    debug_duration_sec: float | None,
    run_sorter: bool,
    alternate_params: bool,
    enable_noisy_segment_cleaning: bool,
    create_analyzer: bool,
    sorter_backend: str,
    skip_existing: bool,
) -> None:
    run_tag = (
        f"debug_{int(debug_duration_sec)}s" if debug_duration_sec is not None else "full"
    )
    output_folder = output_root / animal.animal / f"layout_{layout}" / run_tag
    output_folder.mkdir(parents=True, exist_ok=True)
    with tee_to_log(output_folder / "fig2e_sort_run.log"):
        run_one_job_impl(
            animal=animal,
            layout=layout,
            layout_dir=layout_dir,
            output_root=output_root,
            debug_duration_sec=debug_duration_sec,
            run_sorter=run_sorter,
            alternate_params=alternate_params,
            enable_noisy_segment_cleaning=enable_noisy_segment_cleaning,
            create_analyzer=create_analyzer,
            sorter_backend=sorter_backend,
            skip_existing=skip_existing,
        )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run Figure 2e density-layout sorting jobs."
    )
    parser.add_argument(
        "--animals",
        default="EBL8",
        help="Comma-separated animals or 'all'. Default: EBL8.",
    )
    parser.add_argument(
        "--layouts",
        default="043",
        help="Comma-separated layouts or 'all'. Default: 043.",
    )
    parser.add_argument(
        "--layout-dir",
        type=Path,
        default=LAYOUT_DIR,
        help="Device-channel-mapped layout output directory.",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=DEFAULT_OUTPUT_ROOT,
        help="Root folder for Figure 2e sorting outputs.",
    )
    parser.add_argument(
        "--debug-duration-sec",
        type=float,
        default=None,
        help="Use only the first N seconds of each recording.",
    )
    parser.add_argument(
        "--run-sorter",
        action="store_true",
        help="Actually run MountainSort5. Omit for dry-run metadata/plots only.",
    )
    parser.add_argument(
        "--sorter-backend",
        choices=("spikeinterface", "ms5-direct"),
        default="spikeinterface",
        help=(
            "Use SpikeInterface's sorter wrapper or call mountainsort5 directly. "
            "Use ms5-direct in si_env if spikeinterface.sorters import hangs."
        ),
    )
    parser.add_argument(
        "--alternate-ms5-params",
        action="store_true",
        help="Use the tighter-radius alternate MS5 settings from SortingEBL128 debug mode.",
    )
    parser.add_argument(
        "--enable-noisy-segment-cleaning",
        action="store_true",
        help="Accepted for metadata; standalone noisy-segment cleaning is not implemented yet.",
    )
    parser.add_argument(
        "--create-analyzer",
        action="store_true",
        help=(
            "After sorting, create sorting_analyzer.zarr, compute extensions, "
            "and save SI widget unit summaries plus analyzer waveform plots. "
            "Use si_env for this option."
        ),
    )
    parser.add_argument(
        "--skip-existing",
        action="store_true",
        help=(
            "Skip an animal/layout/run folder when both sorted_sorting and "
            "sorted_units.npz already exist."
        ),
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    os.environ.setdefault("NUMBA_CACHE_DIR", str((args.output_root / ".numba_cache").resolve()))
    animals = parse_csv_choices(args.animals, set(ANIMAL_SESSIONS), "animal")
    layouts = parse_csv_choices(args.layouts, set(LAYOUTS), "layout")
    for animal_name in animals:
        for layout in layouts:
            run_one_job(
                animal=ANIMAL_SESSIONS[animal_name],
                layout=layout,
                layout_dir=args.layout_dir.resolve(),
                output_root=args.output_root.resolve(),
                debug_duration_sec=args.debug_duration_sec,
                run_sorter=args.run_sorter,
                alternate_params=args.alternate_ms5_params,
                enable_noisy_segment_cleaning=args.enable_noisy_segment_cleaning,
                create_analyzer=args.create_analyzer,
                sorter_backend=args.sorter_backend,
                skip_existing=args.skip_existing,
            )


if __name__ == "__main__":
    main()
