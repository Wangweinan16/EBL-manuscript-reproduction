class TeeStream:
    def __init__(self, *streams):
        self.streams = streams

    def write(self, data: str) -> int:
        for stream in self.streams:
            stream.write(data)
            stream.flush()
        return len(data)

    def flush(self) -> None:
        for stream in self.streams:
            stream.flush()


@contextlib.contextmanager
def tee_to_log(log_path: Path):
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("a", encoding="utf-8") as log_file:
        old_stdout = sys.stdout
        old_stderr = sys.stderr
        sys.stdout = TeeStream(old_stdout, log_file)
        sys.stderr = TeeStream(old_stderr, log_file)
        try:
            print(
                f"\n=== Figure 2e sorting log started {datetime.now().isoformat(timespec='seconds')} ===",
                flush=True,
            )
            print(f"Log file: {log_path}", flush=True)
            yield
        finally:
            print(
                f"=== Figure 2e sorting log ended {datetime.now().isoformat(timespec='seconds')} ===\n",
                flush=True,
            )
            sys.stdout = old_stdout
            sys.stderr = old_stderr


@contextlib.contextmanager
def timed_step(step_name: str):
    t0 = time.perf_counter()
    print(f"[step] START {step_name}", flush=True)
    try:
        yield
    finally:
        print(
            f"[step] DONE  {step_name}: {format_elapsed(time.perf_counter() - t0)}",
            flush=True,
        )


